import UIKit
import Capacitor
import AVFoundation

@UIApplicationMain
class AppDelegate: UIResponder, UIApplicationDelegate {

    var window: UIWindow?

    /// Without this the app runs under iOS's default audio session, which
    /// respects the ring/silent switch and allows the system to duck us. That
    /// made the story narration quiet on iPad and silenced the owl game's
    /// Web Audio notes entirely (Web Audio is muted by the silent switch,
    /// while <video> sound is not — which is why only some sounds vanished).
    /// `.playback` is the right category for a storybook: full volume, and it
    /// plays whether or not the device is switched to silent.
    private func configureAudioSession() {
        do {
            try AVAudioSession.sharedInstance().setCategory(.playback, mode: .default, options: [])
            try AVAudioSession.sharedInstance().setActive(true)
        } catch {
            print("[audio] could not set playback session: \(error)")
        }
    }

    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        configureAudioSession()
        return true
    }

